#!/usr/bin/env python3
"""Record upstream and variant-accurate security configuration."""
import argparse, csv, hashlib, json, math, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def delta_msis(B, kmsis, d, q):
    return 2.0 ** ((math.log2(B) ** 2) / (4.0 * d * kmsis * math.log2(q)))


def compute_p2_compact_table():
    d = 64
    q = 1125899906843221
    kmsis = 20
    Z = 2
    stdev1 = 12996365.412649894
    bound_star = math.sqrt(143158532224272924.855956939543963)
    B2 = 2.0 * bound_star
    rows = []
    for k in range(0, 9):
        h = 8 - k
        m1 = 40 + h
        nbin = 8 + h
        nex = m1 + Z
        B1 = 2.0 * stdev1 * math.sqrt(2.0 * (m1 + Z) * d)
        bound = 4.0 * 140.0 * math.sqrt(B1 * B1 + B2 * B2)
        log2_b = math.log2(bound)
        rhf = delta_msis(bound, kmsis, d, q)
        rows.append({
            "disclosed_attributes_k": k,
            "hidden_attributes_h": h,
            "param_symbol": "p2_param" if k == 0 else f"p2_compact{k}_param",
            "relation_shape": [8, m1],
            "m1_secret_polys": m1,
            "nbin_binary_polys": nbin,
            "nex_total_polys": nex,
            "msis_bound_log2": round(log2_b, 6),
            "MSIS_rhf_recomputed": round(rhf, 7),
            "MSIS_rhf_5dec": round(rhf, 5),
            "max_proof_bytes_header": 30064 - 192 * k,
        })
    return rows


def collect():
    vinfo = json.loads((ROOT / 'ACTIVE_VARIANT.json').read_text()) if (ROOT / 'ACTIVE_VARIANT.json').exists() else {'active_variant': 'V0'}
    active_vid = vinfo.get('active_variant', 'V0').upper()
    is_v5 = (active_vid in ['V5','C3','DC3'])
    is_b0 = (active_vid == 'B0')
    is_b1 = (active_vid == 'B1')

    h = ROOT / 'lazer/python/anon_cred/anon_cred_params.h'
    parts = h.read_text().split('// auto-generated by lnp-tbox.sage.')[1:]
    compact_table = compute_p2_compact_table()
    rows = []
    for name, t in zip(['P1', 'P2'], parts):
        def match(p):
            return re.search(p, t)[1]
        if name == 'P1':
            msis_recomp = round(delta_msis(2.0 ** 33.358102, 17, 64, 2199023256889), 7)
            rows.append({
                'component': name,
                'proof_degree': int(match(r'// degree d = (\d+)')),
                'proof_modulus': int(match(r'// modulus q = (\d+)')),
                'm1_secret_polys': 24,
                'binary_polys': 8,
                'knowledge_error_log2_upstream': float(match(r'knowledge error <= 2\^\((-?[\d.]+)\)')),
                'MSIS_original': match(r'under (MSIS[^\n]+)'),
                'MLWE_original': match(r'under (MLWE[^\n]+)'),
                'MSIS_rhf_original': float(match(r'// MSIS root hermite factor: ([\d.]+)')),
                'MSIS_rhf_recomputed': msis_recomp,
                'MLWE_rhf_original': float(match(r'// MLWE root hermite factor: ([\d.]+)')),
                'theoretical_repetition_rate_original': float(match(r'// total = ([\d.]+)')),
            })
        else:
            k_entry = compact_table[3] if is_v5 else compact_table[0]
            rows.append({
                'component': name,
                'proof_degree': int(match(r'// degree d = (\d+)')),
                'proof_modulus': int(match(r'// modulus q = (\d+)')),
                'm1_secret_polys': k_entry['m1_secret_polys'],
                'binary_polys': k_entry['nbin_binary_polys'],
                'knowledge_error_log2_upstream': float(match(r'knowledge error <= 2\^\((-?[\d.]+)\)')),
                'MSIS_original': f"MSIS(20,{k_entry['m1_secret_polys']+64},2^({k_entry['msis_bound_log2']:.4f}))" if is_v5 else match(r'under (MSIS[^\n]+)'),
                'MLWE_original': match(r'under (MLWE[^\n]+)'),
                'MSIS_rhf_original': k_entry['MSIS_rhf_5dec'],
                'MSIS_rhf_recomputed': k_entry['MSIS_rhf_recomputed'],
                'MLWE_rhf_original': float(match(r'// MLWE root hermite factor: ([\d.]+)')),
                'theoretical_repetition_rate_original': float(match(r'// total = ([\d.]+)')),
            })
    return {
        'version': '2.2-e2-variant-aware',
        'active_variant': active_vid,
        'variant_metadata': vinfo,
        'status': 'VARIANT_ACCURATE_CONFIGURATION_RECORDED',
        'upstream_commit': '10eafeca4cd53ff4fc54193dce904dbd0026fefd',
        'upstream_generator_target_bits': 128,
        'target_interpretation': 'original upstream setting, not a new independent concrete-security certification',
        'relation_degree': 64,
        'relation_modulus': 12289,
        'P1_relation_shape': [8, 24],
        'P2_relation_shape': [8, 45] if is_v5 else [8, 48],
        'credential_relation': {
            'P1_relation_shape': [8, 24],
            'P2_relation_shape': [8, 45] if is_v5 else [8, 48],
            'P2_compact_subspace_table': compact_table if is_v5 else None,
        },
        'disclosed_blocks': [0, 4, 5],
        'proofs': rows,
        'parameter_header_sha256': hashlib.sha256(h.read_bytes()).hexdigest(),
        'protocol_modified': is_v5,
        'security_parameters_changed': is_v5,
        'session_extension': False,
        'extra_verification_checks': not is_b0,
        'measurement_only_hooks': is_b0,
        'bugfixes_applied': not is_b0,
        'optimizations_applied': not (is_b0 or is_b1),
        'classical_quantum_new_estimates': 'NOT_RUN_BY_DEFAULT; optional diagnostics never replace upstream configuration',
        'anonymity_unforgeability_zero_knowledge': 'retain original construction assumptions and conditional analysis; no new theorem or numeric whole-protocol bound claimed',
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--output', type=Path, default=ROOT / 'results/security_static')
    a = ap.parse_args()
    a.output.mkdir(parents=True, exist_ok=True)
    d = collect()
    d['version'] = '1.1-e2-frozen-metrics'
    d['classical_quantum_new_estimates'] = 'see security_metrics.json and attack_costs.csv; declared generic models only'
    (a.output / 'security.json').write_text(json.dumps(d, indent=2))
    with (a.output / 'upstream_security_configuration.csv').open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(d['proofs'][0]))
        w.writeheader()
        w.writerows(d['proofs'])
    from security_metrics import write
    write(a.output, d)
    print(f"SECURITY_AND_METRICS_RECORDED [{d['active_variant']}]; target=128; protocol_parameters_changed={d['security_parameters_changed']}")


if __name__ == '__main__':
    main()
